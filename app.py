"""
Pokemon National Dex Scrambler (Streamlit)

Pick a Pokemon (type in the dropdown to filter by name or dex number) and
see every other Pokemon whose dex number uses the same digits (e.g. 0521
Unfezant -> 0125 Electabuzz, 0152 Chikorita, 0215 Sneasel, 0251 Celebi,
0512 Simisage, 1025 Pecharunt), with full stats, types, abilities, height
and weight from PokeAPI (data/pokemon_full.json, regenerated by
scripts/fetch_data.py).
"""
import json
from pathlib import Path

import pandas as pd
import streamlit as st

DATA_PATH = Path(__file__).parent / "data" / "pokemon_full.json"

STAT_COLS = ["hp", "attack", "defense", "sp_attack", "sp_defense", "speed"]
DISPLAY_NAMES = {
    "sprite": "Sprite",
    "dex_str": "Dex",
    "name": "Name",
    "types_str": "Type",
    "hp": "HP",
    "attack": "Atk",
    "defense": "Def",
    "sp_attack": "SpA",
    "sp_defense": "SpD",
    "speed": "Spe",
    "bst": "BST",
    "abilities_str": "Abilities",
    "height_ft": "Height",
    "height_m": "Height (m)",
    "weight_lbs": "Weight (lbs)",
    "weight_kg": "Weight (kg)",
    "generation": "Gen",
    "scrambles_to": "Scrambles To",
}
# The sprite column keeps its raw name ("sprite") in the dataframes: the
# ImageColumn config is keyed by it and supplies the "Sprite" label itself.
# Renaming it to "Sprite" first silently breaks the image rendering.
RENAME = {k: v for k, v in DISPLAY_NAMES.items() if k != "sprite"}
SPRITE_CONFIG = {"sprite": st.column_config.ImageColumn("Sprite",
                                                        width="small")}
# Every column gets an explicit width, computed from the data (longest
# value vs header, ~7.8px per char + 30px padding, min 64px):
#   Dex 4ch->64, Name 12ch->128, Type 19ch->184, stats/BST/Gen <=3ch->64,
#   Abilities 47ch->400, Height 6ch->80, Height (m) header->112,
#   Weight (lbs) header->128, Weight (kg) header->120, Scrambles 73ch->600
COLUMN_CONFIG = {
    **SPRITE_CONFIG,
    "Dex": st.column_config.TextColumn("Dex", width=64),
    "Name": st.column_config.TextColumn("Name", width=128),
    "Type": st.column_config.TextColumn("Type", width=184),
    "HP": st.column_config.NumberColumn("HP", width=64, format="%d"),
    "Atk": st.column_config.NumberColumn("Atk", width=64, format="%d"),
    "Def": st.column_config.NumberColumn("Def", width=64, format="%d"),
    "SpA": st.column_config.NumberColumn("SpA", width=64, format="%d"),
    "SpD": st.column_config.NumberColumn("SpD", width=64, format="%d"),
    "Spe": st.column_config.NumberColumn("Spe", width=64, format="%d"),
    "BST": st.column_config.NumberColumn("BST", width=64, format="%d"),
    "Abilities": st.column_config.TextColumn("Abilities", width=400),
    "Height": st.column_config.TextColumn("Height", width=80),
    "Height (m)": st.column_config.NumberColumn("Height (m)", width=112,
                                                format="%.1f"),
    "Weight (lbs)": st.column_config.NumberColumn("Weight (lbs)",
                                                  width=128, format="%.1f"),
    "Weight (kg)": st.column_config.NumberColumn("Weight (kg)",
                                                 width=120, format="%.1f"),
    "Gen": st.column_config.NumberColumn("Gen", width=64, format="%d"),
    "Scrambles To": st.column_config.TextColumn("Scrambles To", width=600),
}
ONE_DECIMAL = ("Weight (lbs)", "Weight (kg)", "Height (m)")
TYPE_COLORS = {
    "Normal": "#A8A77A", "Fire": "#EE8130", "Water": "#6390F0",
    "Electric": "#F7D02C", "Grass": "#7AC74C", "Ice": "#96D9D6",
    "Fighting": "#C22E28", "Poison": "#A33EA1", "Ground": "#E2BF65",
    "Flying": "#A98FF3", "Psychic": "#F95587", "Bug": "#A6B91A",
    "Rock": "#B6A136", "Ghost": "#735797", "Dragon": "#6F35FC",
    "Dark": "#705746", "Steel": "#B7B7CE", "Fairy": "#D685AD",
}
DARK_TEXT_TYPES = {"Electric", "Ice", "Ground", "Steel", "Fairy"}
STAT_BAR_COLS = [("HP", "hp"), ("Atk", "attack"), ("Def", "defense"),
                 ("SpA", "sp_attack"), ("SpD", "sp_defense"),
                 ("Spe", "speed")]

# Every column the explorer can show, in canonical order. Sprite, Dex and
# Name are permanent; the rest are pickable.
PERMANENT_COLS = ["sprite", "dex_str", "name"]
ALL_COLS = (PERMANENT_COLS + ["types_str"] + STAT_COLS +
            ["bst", "abilities_str", "height_ft", "weight_lbs",
             "height_m", "weight_kg", "generation", "scrambles_to"])
PICKABLE_COLS = [c for c in ALL_COLS if c not in PERMANENT_COLS]
DEFAULT_PICKED = [c for c in PICKABLE_COLS
                  if c not in ("height_m", "weight_kg")]
# Columns for the quick-search table: the searched Pokemon (top row,
# highlighted) and its scrambles in ONE table so they share a scroll.
RESULT_COLS = (PERMANENT_COLS + ["types_str"] + STAT_COLS +
               ["bst", "abilities_str", "height_ft", "weight_lbs",
                "generation"])
ALL_TYPES = [
    "Normal", "Fire", "Water", "Electric", "Grass", "Ice", "Fighting",
    "Poison", "Ground", "Flying", "Psychic", "Bug", "Rock", "Ghost",
    "Dragon", "Dark", "Steel", "Fairy",
]


@st.cache_data
def load_data() -> pd.DataFrame:
    raw = json.loads(DATA_PATH.read_text(encoding="utf-8"))
    df = pd.DataFrame(raw)
    df["types_str"] = df["types"].apply(lambda ts: " / ".join(ts))

    def abilities_str(row):
        parts = list(row["abilities"])
        ha = row["hidden_ability"]
        # JSON null arrives as float NaN via pandas; only real strings count
        if isinstance(ha, str) and ha:
            parts.append(f"{ha} (HA)")
        return ", ".join(parts)

    df["abilities_str"] = df.apply(abilities_str, axis=1)
    return df


@st.cache_data
def scramble_map(dex_strs: tuple) -> dict:
    """dex_str -> list of dex_strs whose digits are a permutation of it."""
    by_digits = {}
    for dex_str in dex_strs:
        key = tuple(sorted(dex_str))
        by_digits.setdefault(key, []).append(dex_str)
    return {
        dex_str: sorted(d for d in by_digits[tuple(sorted(dex_str))]
                        if d != dex_str)
        for dex_str in dex_strs
    }


@st.cache_data
def dex_labels(dex_strs: tuple, names: tuple):
    """Dropdown labels '0521 Unfezant' (type to filter by name or number)
    plus a label -> dex lookup."""
    labels = tuple(f"{d} {n}" for d, n in zip(dex_strs, names))
    lookup = {label: int(label.split(" ", 1)[0])
              for label in labels}
    return labels, lookup


def styled(display: pd.DataFrame, highlight_first: bool = False):
    """The Styler every table goes through: explicit one-decimal formats
    (a bare Styler renders floats as 1.100000) and optionally the gold
    highlight on the first row. (Cell alignment is NOT set here: the
    Streamlit grid ignores Styler text-align and hard-codes numbers
    right / text left — verified on the live app 2026-10-30.)"""
    styler = display.style.format(
        {c: "{:.1f}" for c in ONE_DECIMAL if c in display.columns})
    if highlight_first and not display.empty:
        def style_row(row):
            css = ("background-color: rgba(250, 180, 0, 0.30); "
                   "font-weight: bold")
            return [css if row.name == display.index[0] else ""
                    for _ in row]
        styler = styler.apply(style_row, axis=1)
    return styler


def show_table(frame: pd.DataFrame, cols: list, highlight_first: bool = False):
    display = frame[cols].rename(columns=RENAME)
    st.dataframe(
        styled(display, highlight_first),
        hide_index=True,
        width="stretch",
        column_config=COLUMN_CONFIG,
    )


def type_chip(type_name: str) -> str:
    fg = "#1A1A1A" if type_name in DARK_TEXT_TYPES else "#FFFFFF"
    return (f'<span style="background:{TYPE_COLORS[type_name]};color:{fg};'
            f'padding:2px 10px;border-radius:999px;font-size:0.8rem;'
            f'font-weight:600;margin-right:6px">{type_name}</span>')


def stat_bar(label: str, value: int, max_value: int, bold: bool = False) -> str:
    pct = round(value / max_value * 100, 1)
    weight = "700" if bold else "400"
    return (
        '<div style="display:flex;align-items:center;gap:8px;margin:2px 0">'
        f'<span style="width:28px;font-size:0.8rem;opacity:0.75;'
        f'font-weight:{weight}">{label}</span>'
        '<span style="flex:1;background:rgba(140,150,170,0.25);'
        'border-radius:4px;height:7px">'
        f'<span style="display:block;width:{pct}%;background:#F5B301;'
        'height:7px;border-radius:4px"></span></span>'
        f'<span style="width:32px;text-align:right;font-size:0.85rem;'
        f'font-weight:{weight}">{value}</span></div>')


def hero_card(row) -> None:
    """A profile card for the searched Pokémon above its scramble table:
    official artwork, type chips, meta line and stat bars."""
    artwork = row["sprite"].replace(
        "/sprites/pokemon/", "/sprites/pokemon/other/official-artwork/")
    chips = "".join(type_chip(t) for t in row["types"])
    bars = "".join(stat_bar(label, int(row[col]), 255)
                   for label, col in STAT_BAR_COLS)
    bars += stat_bar("BST", int(row["bst"]), 720, bold=True)
    st.markdown(
        '<div style="display:flex;gap:20px;align-items:flex-start;'
        'flex-wrap:wrap">'
        f'<img src="{artwork}" onerror="this.style.display=\'none\'" '
        'style="width:128px;height:128px;object-fit:contain">'
        '<div style="flex:1 1 240px">'
        f'<div style="font-size:1.45rem;font-weight:700;line-height:1.2">'
        f'{row["name"]} <span style="opacity:0.6;font-weight:400">'
        f'#{row["dex_str"]}</span></div>'
        f'<div style="margin:6px 0 4px">{chips}</div>'
        f'<div style="opacity:0.75;font-size:0.9rem">'
        f'{row["height_ft"]} · {row["weight_lbs"]:.1f} lbs '
        f'({row["weight_kg"]:.1f} kg) · Gen {int(row["generation"])}</div>'
        f'<div style="opacity:0.75;font-size:0.9rem">Abilities: '
        f'{row["abilities_str"]}</div>'
        '</div>'
        # Stat bars sit in-line as a third column on wide screens
        # (capped at 460px) and wrap full-width under the info on phones
        f'<div style="flex:1 1 300px;max-width:460px">{bars}</div>'
        '</div>',
        unsafe_allow_html=True,
    )


st.set_page_config(page_title="Pokemon National Dex Scrambler",
                   page_icon="🎲", layout="wide")
st.title("Pokémon National Dex Scrambler")
st.caption("Every Pokémon whose National Dex number is an anagram of "
           "another's — with full stats, types, abilities and sizes.")
st.divider()

df = load_data()
smap = scramble_map(tuple(df["dex_str"]))
names_by_dex = dict(zip(df["dex_str"], df["name"]))
df["scrambles_to"] = df["dex_str"].apply(
    lambda d: ", ".join(names_by_dex[t] for t in smap[d]) if smap[d] else "—"
)
labels, label_to_dex = dex_labels(tuple(df["dex_str"]), tuple(df["name"]))

# ---------------------------------------------------------------- quick search
st.header("Quick Scrambler Search")
st.caption("Start typing a name or dex number in a box and pick from the "
           "filtered list — up to three Pokémon at once. Each result is a "
           "single table: your Pokémon highlighted on top, then every "
           "Pokémon whose dex number is a rearrangement of the same "
           "digits — so everything scrolls together.")

for slot in range(1, 4):
    with st.container(border=True):
        pick = st.selectbox(
            f"Search {slot}",
            labels,
            index=None,
            placeholder="Type a name or dex number…",
            key=f"quick{slot}",
        )
        if pick is None:
            continue
        dex = label_to_dex[pick]
        source = df[df["dex"] == dex]
        hero_card(source.iloc[0])
        matches = df[df["dex_str"].isin(smap[f"{dex:04d}"])]
        matches = matches.sort_values("dex")
        combined = pd.concat([source, matches], ignore_index=True)

        show_table(combined, RESULT_COLS, highlight_first=True)
        if matches.empty:
            st.info("No valid Pokémon matches found.")

# ---------------------------------------------------------------- full explorer
st.header("Full Dex Explorer")
st.caption("The whole National Dex with its scramble matches. Click any "
           "column header to sort. Sprite, Dex and Name are always shown; "
           "pick the rest.")

with st.expander("Filters & columns", expanded=False):
    f1, f2, f3 = st.columns(3)
    with f1:
        search_q = st.text_input("Search by name or dex number",
                                 placeholder="e.g. char, 0521, 25")
    with f2:
        type_sel = st.multiselect("Type", ALL_TYPES)
    with f3:
        gen_sel = st.multiselect("Generation",
                                 sorted(df["generation"].unique()))

    bst_min, bst_max = int(df["bst"].min()), int(df["bst"].max())
    bst_range = st.slider("BST range", bst_min, bst_max, (bst_min, bst_max))

    chosen_cols = st.multiselect(
        "Columns", PICKABLE_COLS, default=DEFAULT_PICKED,
        format_func=lambda c: DISPLAY_NAMES[c],
    )
show_cols = PERMANENT_COLS + [c for c in ALL_COLS
                              if c in chosen_cols and c not in PERMANENT_COLS]

view = df.copy()
if search_q.strip():
    q = search_q.strip()
    name_hit = view["name"].str.contains(q, case=False, na=False)
    if q.isdigit():
        # match the zero-padded dex ("0521") or a partial one ("52")
        dex_hit = (view["dex_str"].str.contains(q.zfill(4)) |
                   view["dex_str"].str.contains(q))
        view = view[name_hit | dex_hit]
    else:
        view = view[name_hit]
if type_sel:
    view = view[view["types"].apply(lambda ts: any(t in ts for t in type_sel))]
if gen_sel:
    view = view[view["generation"].isin(gen_sel)]
view = view[(view["bst"] >= bst_range[0]) & (view["bst"] <= bst_range[1])]

st.dataframe(
    styled(view[show_cols].rename(columns=RENAME)),
    hide_index=True,
    width="stretch",
    height=600,
    column_config=COLUMN_CONFIG,
)
st.caption(f"{len(view)} of {len(df)} Pokémon shown · Data: PokéAPI "
           "(current-generation base stats, base forms)")
