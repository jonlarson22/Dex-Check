"""
Pokemon National Dex Scrambler (Streamlit)

Pick a Pokemon (type in the dropdown to filter by name or dex number) and
see every other Pokemon whose dex number uses the same digits (e.g. 0521
Unfezant -> 0125 Electabuzz, 0152 Chikorita, 0215 Sneasel, 0251 Celebi,
0512 Simisage, 1025 Pecharunt), with full stats, types, abilities, height
and weight from PokeAPI (data/pokemon_full.json, regenerated by
scripts/fetch_data.py).
"""
import json
from pathlib import Path

import pandas as pd
import streamlit as st

DATA_PATH = Path(__file__).parent / "data" / "pokemon_full.json"

STAT_COLS = ["hp", "attack", "defense", "sp_attack", "sp_defense", "speed"]
DISPLAY_NAMES = {
    "sprite": "Sprite",
    "dex_str": "Dex",
    "name": "Name",
    "types_str": "Type",
    "hp": "HP",
    "attack": "Atk",
    "defense": "Def",
    "sp_attack": "SpA",
    "sp_defense": "SpD",
    "speed": "Spe",
    "bst": "BST",
    "abilities_str": "Abilities",
    "height_ft": "Height",
    "height_m": "Height (m)",
    "weight_lbs": "Weight (lbs)",
    "weight_kg": "Weight (kg)",
    "generation": "Gen",
    "scrambles_to": "Scrambles To",
}
# The sprite column keeps its raw name ("sprite") in the dataframes: the
# ImageColumn config is keyed by it and supplies the "Sprite" label itself.
# Renaming it to "Sprite" first silently breaks the image rendering.
RENAME = {k: v for k, v in DISPLAY_NAMES.items() if k != "sprite"}
SPRITE_CONFIG = {"sprite": st.column_config.ImageColumn("Sprite",
                                                        width="small")}
# Shared by every table: roomier text columns and one-decimal formats for
# the measured quantities. Widths are sized from the data: the longest
# ability list is 47 chars, the longest Scrambles To list is 73 chars.
MEASURE_CONFIG = {
    "Abilities": st.column_config.TextColumn("Abilities", width=400),
    "Scrambles To": st.column_config.TextColumn("Scrambles To", width=560),
    "Weight (lbs)": st.column_config.NumberColumn("Weight (lbs)",
                                                  format="%.1f"),
    "Weight (kg)": st.column_config.NumberColumn("Weight (kg)",
                                                 format="%.1f"),
    "Height (m)": st.column_config.NumberColumn("Height (m)",
                                                format="%.1f"),
}

# Every column the explorer can show, in canonical order. Sprite, Dex and
# Name are permanent; the rest are pickable.
PERMANENT_COLS = ["sprite", "dex_str", "name"]
ALL_COLS = (PERMANENT_COLS + ["types_str"] + STAT_COLS +
            ["bst", "abilities_str", "height_ft", "weight_lbs",
             "height_m", "weight_kg", "generation", "scrambles_to"])
PICKABLE_COLS = [c for c in ALL_COLS if c not in PERMANENT_COLS]
DEFAULT_PICKED = [c for c in PICKABLE_COLS
                  if c not in ("height_m", "weight_kg")]
# Columns for the quick-search table: the searched Pokemon (top row,
# highlighted) and its scrambles in ONE table so they share a scroll.
RESULT_COLS = (PERMANENT_COLS + ["types_str"] + STAT_COLS +
               ["bst", "abilities_str", "height_ft", "weight_lbs",
                "generation"])
ALL_TYPES = [
    "Normal", "Fire", "Water", "Electric", "Grass", "Ice", "Fighting",
    "Poison", "Ground", "Flying", "Psychic", "Bug", "Rock", "Ghost",
    "Dragon", "Dark", "Steel", "Fairy",
]


@st.cache_data
def load_data() -> pd.DataFrame:
    raw = json.loads(DATA_PATH.read_text(encoding="utf-8"))
    df = pd.DataFrame(raw)
    df["types_str"] = df["types"].apply(lambda ts: " / ".join(ts))

    def abilities_str(row):
        parts = list(row["abilities"])
        ha = row["hidden_ability"]
        # JSON null arrives as float NaN via pandas; only real strings count
        if isinstance(ha, str) and ha:
            parts.append(f"{ha} (HA)")
        return ", ".join(parts)

    df["abilities_str"] = df.apply(abilities_str, axis=1)
    return df


@st.cache_data
def scramble_map(dex_strs: tuple) -> dict:
    """dex_str -> list of dex_strs whose digits are a permutation of it."""
    by_digits = {}
    for dex_str in dex_strs:
        key = tuple(sorted(dex_str))
        by_digits.setdefault(key, []).append(dex_str)
    return {
        dex_str: sorted(d for d in by_digits[tuple(sorted(dex_str))]
                        if d != dex_str)
        for dex_str in dex_strs
    }


@st.cache_data
def dex_labels(dex_strs: tuple, names: tuple):
    """Dropdown labels '0521 Unfezant' (type to filter by name or number)
    plus a label -> dex lookup."""
    labels = tuple(f"{d} {n}" for d, n in zip(dex_strs, names))
    lookup = {label: int(label.split(" ", 1)[0])
              for label in labels}
    return labels, lookup


def show_table(frame: pd.DataFrame, cols: list, highlight_first: bool = False):
    display = frame[cols].rename(columns=RENAME)
    # Always go through a Styler so number formats are explicit: a bare
    # Styler renders floats with 6 decimals (1.100000) instead of the
    # grid's trimmed format.
    styler = display.style.format(
        {c: "{:.1f}" for c in ("Weight (lbs)", "Weight (kg)", "Height (m)")
         if c in display.columns}
    )
    if highlight_first and not display.empty:
        def style_row(row):
            css = ("background-color: rgba(250, 180, 0, 0.30); "
                   "font-weight: bold")
            return [css if row.name == display.index[0] else ""
                    for _ in row]
        styler = styler.apply(style_row, axis=1)
    config = dict(MEASURE_CONFIG)
    if "sprite" in cols:
        config.update(SPRITE_CONFIG)
    st.dataframe(
        styler,
        hide_index=True,
        width="stretch",
        column_config=config,
    )


st.set_page_config(page_title="Pokemon National Dex Scrambler",
                   page_icon="🎲", layout="wide")
st.title("Pokémon National Dex Scrambler")

df = load_data()
smap = scramble_map(tuple(df["dex_str"]))
names_by_dex = dict(zip(df["dex_str"], df["name"]))
df["scrambles_to"] = df["dex_str"].apply(
    lambda d: ", ".join(names_by_dex[t] for t in smap[d]) if smap[d] else "—"
)
labels, label_to_dex = dex_labels(tuple(df["dex_str"]), tuple(df["name"]))

# ---------------------------------------------------------------- quick search
st.header("Quick Scrambler Search")
st.caption("Start typing a name or dex number in a box and pick from the "
           "filtered list — up to three Pokémon at once. Each result is a "
           "single table: your Pokémon highlighted on top, then every "
           "Pokémon whose dex number is a rearrangement of the same "
           "digits — so everything scrolls together.")

for slot in range(1, 4):
    with st.container(border=True):
        pick = st.selectbox(
            f"Search {slot}",
            labels,
            index=None,
            placeholder="Type a name or dex number…",
            key=f"quick{slot}",
        )
        if pick is None:
            continue
        dex = label_to_dex[pick]
        source = df[df["dex"] == dex]
        matches = df[df["dex_str"].isin(smap[f"{dex:04d}"])]
        matches = matches.sort_values("dex")
        combined = pd.concat([source, matches], ignore_index=True)

        show_table(combined, RESULT_COLS, highlight_first=True)
        if matches.empty:
            st.info("No valid Pokémon matches found.")

# ---------------------------------------------------------------- full explorer
st.header("Full Dex Explorer")
st.caption("The whole National Dex with its scramble matches. Click any "
           "column header to sort. Sprite, Dex and Name are always shown; "
           "pick the rest.")

f1, f2, f3 = st.columns(3)
with f1:
    search_q = st.text_input("Search by name or dex number",
                             placeholder="e.g. char, 0521, 25")
with f2:
    type_sel = st.multiselect("Type", ALL_TYPES)
with f3:
    gen_sel = st.multiselect("Generation", sorted(df["generation"].unique()))

bst_min, bst_max = int(df["bst"].min()), int(df["bst"].max())
bst_range = st.slider("BST range", bst_min, bst_max, (bst_min, bst_max))

chosen_cols = st.multiselect(
    "Columns", PICKABLE_COLS, default=DEFAULT_PICKED,
    format_func=lambda c: DISPLAY_NAMES[c],
)
show_cols = PERMANENT_COLS + [c for c in ALL_COLS
                              if c in chosen_cols and c not in PERMANENT_COLS]

view = df.copy()
if search_q.strip():
    q = search_q.strip()
    name_hit = view["name"].str.contains(q, case=False, na=False)
    if q.isdigit():
        # match the zero-padded dex ("0521") or a partial one ("52")
        dex_hit = (view["dex_str"].str.contains(q.zfill(4)) |
                   view["dex_str"].str.contains(q))
        view = view[name_hit | dex_hit]
    else:
        view = view[name_hit]
if type_sel:
    view = view[view["types"].apply(lambda ts: any(t in ts for t in type_sel))]
if gen_sel:
    view = view[view["generation"].isin(gen_sel)]
view = view[(view["bst"] >= bst_range[0]) & (view["bst"] <= bst_range[1])]

st.dataframe(
    view[show_cols].rename(columns=RENAME),
    hide_index=True,
    width="stretch",
    height=600,
    column_config={**SPRITE_CONFIG, **MEASURE_CONFIG},
)
st.caption(f"{len(view)} of {len(df)} Pokémon shown · Data: PokéAPI "
           "(current-generation base stats, base forms)")
