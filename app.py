"""
Pokemon National Dex Scrambler (Streamlit)

Search by name or dex number and see every other Pokemon whose dex number
uses the same digits (e.g. 0521 Unfezant -> 0125 Electabuzz, 0152 Chikorita,
0215 Sneasel, 0251 Celebi, 0512 Simisage, 1025 Pecharunt), with full stats,
types, abilities, height and weight from PokeAPI (data/pokemon_full.json,
regenerated by scripts/fetch_data.py).
"""
import json
import re
import unicodedata
from pathlib import Path

import pandas as pd
import streamlit as st

DATA_PATH = Path(__file__).parent / "data" / "pokemon_full.json"

STAT_COLS = ["hp", "attack", "defense", "sp_attack", "sp_defense", "speed"]
DISPLAY_NAMES = {
    "sprite": "Sprite",
    "dex_str": "Dex",
    "name": "Name",
    "types_str": "Type",
    "hp": "HP",
    "attack": "Atk",
    "defense": "Def",
    "sp_attack": "SpA",
    "sp_defense": "SpD",
    "speed": "Spe",
    "bst": "BST",
    "abilities_str": "Abilities",
    "height_ft": "Height",
    "height_m": "Height (m)",
    "weight_lbs": "Weight (lbs)",
    "weight_kg": "Weight (kg)",
    "generation": "Gen",
    "scrambles_to": "Scrambles To",
}
# Every column the explorer can show, in canonical order.
ALL_COLS = (["sprite", "dex_str", "name", "types_str"] + STAT_COLS +
            ["bst", "abilities_str", "height_ft", "weight_lbs",
             "height_m", "weight_kg", "generation", "scrambles_to"])
# Columns used for the quick-search tables (searched Pokemon + its matches).
RESULT_COLS = (["sprite", "dex_str", "name", "types_str"] + STAT_COLS +
               ["bst", "abilities_str", "height_ft", "weight_lbs",
                "generation"])
DEFAULT_EXPLORER_COLS = [c for c in ALL_COLS
                         if c not in ("height_m", "weight_kg")]
ALL_TYPES = [
    "Normal", "Fire", "Water", "Electric", "Grass", "Ice", "Fighting",
    "Poison", "Ground", "Flying", "Psychic", "Bug", "Rock", "Ghost",
    "Dragon", "Dark", "Steel", "Fairy",
]


@st.cache_data
def load_data() -> pd.DataFrame:
    raw = json.loads(DATA_PATH.read_text(encoding="utf-8"))
    df = pd.DataFrame(raw)
    df["types_str"] = df["types"].apply(lambda ts: " / ".join(ts))

    def abilities_str(row):
        parts = list(row["abilities"])
        if row["hidden_ability"]:
            parts.append(f"{row['hidden_ability']} (HA)")
        return ", ".join(parts)

    df["abilities_str"] = df.apply(abilities_str, axis=1)
    return df


@st.cache_data
def scramble_map(dex_strs: tuple) -> dict:
    """dex_str -> list of dex_strs whose digits are a permutation of it."""
    by_digits = {}
    for dex_str in dex_strs:
        key = tuple(sorted(dex_str))
        by_digits.setdefault(key, []).append(dex_str)
    return {
        dex_str: sorted(d for d in by_digits[tuple(sorted(dex_str))]
                        if d != dex_str)
        for dex_str in dex_strs
    }


def normalize(text: str) -> str:
    """Fold accents and drop punctuation/spaces so 'mr mime', 'mrmime' and
    'Mr. Mime' all compare equal."""
    folded = unicodedata.normalize("NFKD", text)
    folded = "".join(c for c in folded if not unicodedata.combining(c))
    return re.sub(r"[^a-z0-9]", "", folded.lower())


def resolve_query(df: pd.DataFrame, query: str):
    """Resolve a quick-search query to candidate rows.

    Returns (kind, rows): kind is 'dex', 'exact', 'partial' or 'none'.
    A pure-digit query is always treated as a dex number.
    """
    q = query.strip()
    if not q:
        return "none", df.iloc[0:0]
    if q.isdigit():
        hit = df[df["dex"] == int(q)]
        return ("dex", hit) if not hit.empty else ("none", hit)
    nq = normalize(q)
    norm_names = df["name"].apply(normalize)
    exact = df[norm_names == nq]
    if not exact.empty:
        return "exact", exact
    partial = df[norm_names.str.contains(nq, na=False)]
    return ("partial", partial) if not partial.empty else ("none", partial)


def show_table(frame: pd.DataFrame, cols: list):
    config = {}
    if "sprite" in cols:
        config["sprite"] = st.column_config.ImageColumn("Sprite",
                                                        width="small")
    st.dataframe(
        frame[cols].rename(columns=DISPLAY_NAMES),
        hide_index=True,
        width="stretch",
        column_config=config,
    )


st.set_page_config(page_title="Pokemon National Dex Scrambler",
                   page_icon="🎲", layout="wide")
st.title("Pokémon National Dex Scrambler")

df = load_data()
smap = scramble_map(tuple(df["dex_str"]))
names_by_dex = dict(zip(df["dex_str"], df["name"]))
df["scrambles_to"] = df["dex_str"].apply(
    lambda d: ", ".join(names_by_dex[t] for t in smap[d]) if smap[d] else "—"
)

# ---------------------------------------------------------------- quick search
st.header("Quick Scrambler Search")
st.caption("Search by name or dex number — up to three at once. Each search "
           "shows the Pokémon's full details, then every Pokémon whose dex "
           "number is a rearrangement of the same digits.")

for slot in range(1, 4):
    with st.container(border=True):
        query = st.text_input(
            f"Search {slot} — name or dex number",
            value="",
            placeholder="e.g. Unfezant, 521, or pika",
            key=f"quick{slot}",
        )
        if not query.strip():
            continue
        kind, hits = resolve_query(df, query)
        if kind == "none":
            st.warning(f"No Pokémon found for “{query}”.")
            continue
        if len(hits) > 1:
            labels = {f"{r.dex_str} {r.name}": r.dex for r in hits.itertuples()}
            pick = st.selectbox(
                "Several matches — which one?",
                list(labels),
                key=f"pick{slot}",
            )
            source = df[df["dex"] == labels[pick]].iloc[0]
        else:
            source = hits.iloc[0]

        dex = int(source["dex"])
        st.markdown(f"**You searched: {source['dex_str']} {source['name']}**")
        show_table(df[df["dex"] == dex], RESULT_COLS)

        matches = df[df["dex_str"].isin(smap[f"{dex:04d}"])].sort_values("dex")
        st.markdown(f"**Scrambles to ({len(matches)}):**")
        if matches.empty:
            st.info("No valid Pokémon matches found.")
        else:
            show_table(matches, RESULT_COLS)

# ---------------------------------------------------------------- full explorer
st.header("Full Dex Explorer")
st.caption("The whole National Dex with its scramble matches. Click any "
           "column header to sort, and pick exactly which columns to show.")

f1, f2, f3 = st.columns(3)
with f1:
    search_q = st.text_input("Search by name or dex number",
                             placeholder="e.g. char, 0521, 25")
with f2:
    type_sel = st.multiselect("Type", ALL_TYPES)
with f3:
    gen_sel = st.multiselect("Generation", sorted(df["generation"].unique()))

bst_min, bst_max = int(df["bst"].min()), int(df["bst"].max())
bst_range = st.slider("BST range", bst_min, bst_max, (bst_min, bst_max))

chosen_cols = st.multiselect(
    "Columns", ALL_COLS, default=DEFAULT_EXPLORER_COLS,
    format_func=lambda c: DISPLAY_NAMES[c],
)
show_cols = [c for c in ALL_COLS if c in chosen_cols]

view = df.copy()
if search_q.strip():
    q = search_q.strip()
    name_hit = view["name"].str.contains(q, case=False, na=False)
    if q.isdigit():
        # match the zero-padded dex ("0521") or a partial one ("52")
        dex_hit = (view["dex_str"].str.contains(q.zfill(4)) |
                   view["dex_str"].str.contains(q))
        view = view[name_hit | dex_hit]
    else:
        view = view[name_hit]
if type_sel:
    view = view[view["types"].apply(lambda ts: any(t in ts for t in type_sel))]
if gen_sel:
    view = view[view["generation"].isin(gen_sel)]
view = view[(view["bst"] >= bst_range[0]) & (view["bst"] <= bst_range[1])]

if not show_cols:
    st.warning("Pick at least one column to show.")
else:
    st.dataframe(
        view[show_cols].rename(columns=DISPLAY_NAMES),
        hide_index=True,
        width="stretch",
        height=600,
        column_config=(
            {"sprite": st.column_config.ImageColumn("Sprite", width="small")}
            if "sprite" in show_cols else {}
        ),
    )
st.caption(f"{len(view)} of {len(df)} Pokémon shown · Data: PokéAPI "
           "(current-generation base stats, base forms)")
