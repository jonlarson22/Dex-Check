"""
Pokemon National Dex Scrambler (Streamlit)

Type a dex number and see every other Pokemon whose dex number uses the
same digits (e.g. 0101 Electrode -> 0011 Metapod, 0110 Weezing,
1001 Wo-Chien, 1010 Iron Leaves), now with full stats, types, abilities,
height and weight from PokeAPI (data/pokemon_full.json, regenerated by
scripts/fetch_data.py).
"""
import json
from pathlib import Path

import pandas as pd
import streamlit as st

DATA_PATH = Path(__file__).parent / "data" / "pokemon_full.json"

STAT_COLS = ["hp", "attack", "defense", "sp_attack", "sp_defense", "speed"]
DISPLAY_NAMES = {
    "dex_str": "Dex",
    "name": "Name",
    "types_str": "Type",
    "hp": "HP",
    "attack": "Atk",
    "defense": "Def",
    "sp_attack": "SpA",
    "sp_defense": "SpD",
    "speed": "Spe",
    "bst": "BST",
    "height_ft": "Height",
    "height_m": "Height (m)",
    "weight_lbs": "Weight (lbs)",
    "weight_kg": "Weight (kg)",
    "abilities_str": "Abilities",
    "generation": "Gen",
    "scrambles_to": "Scrambles To",
}
ALL_TYPES = [
    "Normal", "Fire", "Water", "Electric", "Grass", "Ice", "Fighting",
    "Poison", "Ground", "Flying", "Psychic", "Bug", "Rock", "Ghost",
    "Dragon", "Dark", "Steel", "Fairy",
]


@st.cache_data
def load_data() -> pd.DataFrame:
    raw = json.loads(DATA_PATH.read_text(encoding="utf-8"))
    df = pd.DataFrame(raw)
    df["types_str"] = df["types"].apply(lambda ts: " / ".join(ts))

    def abilities_str(row):
        parts = list(row["abilities"])
        if row["hidden_ability"]:
            parts.append(f"{row['hidden_ability']} (HA)")
        return ", ".join(parts)

    df["abilities_str"] = df.apply(abilities_str, axis=1)
    return df


@st.cache_data
def scramble_map(dex_strs: tuple) -> dict:
    """dex_str -> list of dex_strs whose digits are a permutation of it."""
    by_digits = {}
    for dex_str in dex_strs:
        key = tuple(sorted(dex_str))
        by_digits.setdefault(key, []).append(dex_str)
    return {
        dex_str: sorted(d for d in by_digits[tuple(sorted(dex_str))]
                        if d != dex_str)
        for dex_str in dex_strs
    }


def scramble_rows(df: pd.DataFrame, smap: dict, dex: int) -> pd.DataFrame:
    padded = f"{dex:04d}"
    targets = smap.get(padded, [])
    return df[df["dex_str"].isin(targets)].sort_values("dex")


def result_table(df: pd.DataFrame):
    cols = ["sprite", "dex_str", "name", "types_str"] + STAT_COLS + ["bst"]
    st.dataframe(
        df[cols].rename(columns=DISPLAY_NAMES),
        hide_index=True,
        width="stretch",
        column_config={
            "sprite": st.column_config.ImageColumn("Sprite", width="small"),
        },
    )


st.set_page_config(page_title="Pokemon National Dex Scrambler",
                   page_icon="🎲", layout="wide")
st.title("Pokémon National Dex Scrambler")

df = load_data()
smap = scramble_map(tuple(df["dex_str"]))
df["scrambles_to"] = df["dex_str"].apply(
    lambda d: ", ".join(
        f"{df.loc[df['dex_str'] == t, 'name'].iloc[0]}" for t in smap[d]
    ) if smap[d] else "—"
)
by_dex = df.set_index("dex")

# ---------------------------------------------------------------- quick search
st.header("Quick Scrambler Search")
st.caption("Enter up to three dex numbers. Each one lists every Pokémon whose "
           "dex number is a rearrangement of the same digits.")

for slot in range(1, 4):
    with st.container(border=True):
        dex = st.number_input(
            f"Dex Number {slot}", min_value=1, max_value=1025, value=None,
            step=1, placeholder="e.g. 101", key=f"quick{slot}",
        )
        if dex is not None:
            source = by_dex.loc[dex]
            st.markdown(
                f"**{source['dex_str']} {source['name']}** — "
                f"{source['types_str']} · BST {source['bst']} · "
                f"{source['height_ft']} · {source['weight_lbs']} lbs"
            )
            matches = scramble_rows(df, smap, int(dex))
            if matches.empty:
                st.info("No valid Pokémon matches found.")
            else:
                result_table(matches)

# ---------------------------------------------------------------- full explorer
st.header("Full Dex Explorer")
st.caption("The whole National Dex with its scramble matches. Click any column "
           "header to sort.")

f1, f2, f3 = st.columns(3)
with f1:
    name_q = st.text_input("Search by name", placeholder="e.g. char")
with f2:
    type_sel = st.multiselect("Type", ALL_TYPES)
with f3:
    gen_sel = st.multiselect("Generation", sorted(df["generation"].unique()))

bst_min, bst_max = int(df["bst"].min()), int(df["bst"].max())
bst_range = st.slider("BST range", bst_min, bst_max, (bst_min, bst_max))

optional_cols = ["abilities_str", "height_ft", "weight_lbs", "generation",
                 "height_m", "weight_kg"]
show_cols = st.multiselect(
    "Extra columns", optional_cols,
    default=["abilities_str", "height_ft", "weight_lbs", "generation"],
    format_func=lambda c: DISPLAY_NAMES[c],
)

view = df.copy()
if name_q:
    view = view[view["name"].str.contains(name_q, case=False, na=False)]
if type_sel:
    view = view[view["types"].apply(lambda ts: any(t in ts for t in type_sel))]
if gen_sel:
    view = view[view["generation"].isin(gen_sel)]
view = view[(view["bst"] >= bst_range[0]) & (view["bst"] <= bst_range[1])]

cols = (["sprite", "dex_str", "name", "types_str"] + STAT_COLS +
        ["bst"] + show_cols + ["scrambles_to"])
st.dataframe(
    view[cols].rename(columns=DISPLAY_NAMES),
    hide_index=True,
    width="stretch",
    height=600,
    column_config={
        "sprite": st.column_config.ImageColumn("Sprite", width="small"),
    },
)
st.caption(f"{len(view)} of {len(df)} Pokémon shown · Data: PokéAPI "
           "(current-generation base stats, base forms) · "
           "Height/weight shown in imperial by default; add the metric "
           "columns above if you want them.")
